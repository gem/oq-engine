            # them once per compute call and reuse across all IMTs
            site_feat_idx = _assign_feature_indices(
                self.att_site_tree, ctx.lon, ctx.lat)
            event_feat_idx = _assign_feature_indices(
                self.att_event_tree, ctx.hypo_lon, ctx.hypo_lat)
            tec_feat_idx = _assign_feature_indices(
                self.tec_tree, ctx.hypo_lon, ctx.hypo_lat)
            
            for m, imt in enumerate(imts):
                C = self.COEFFS[imt]
                extra = {}
                phi_s2s = None
                c3 = get_distance_coefficients_2(
                    self.att_site_vals, site_feat_idx,
                    self.att_event_vals, event_feat_idx,
                    self.delta_c3_epsilon, C, str(imt), ctx)

                dl2l = get_dl2l(self.tec_vals, tec_feat_idx, str(imt),
                                self.delta_l2l_epsilon)

                fp = get_distance_term(self.kind, c3, self.c3_epsilon,
                                    C, ctx, imt)

                mean[m] = (get_magnitude_scaling(C, ctx.mag) + fp + dl2l +
                       get_site_amplification(self.kind, extra, C, ctx, imt))


