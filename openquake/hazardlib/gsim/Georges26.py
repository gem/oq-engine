CONSTANTS = {"Mref": 4.5, "Rref": 30., "Mh": 5.7,
             "h_D10": 4.0, "h_10D20": 8.0, "h_D20": 12.0}



def _get_h(C, hypo_depth):
    """
    Returns the depth-specific coefficient
    """
    return np.where(
        hypo_depth <= 10.,
        CONSTANTS["h_D10"],
        np.where(hypo_depth > 20., CONSTANTS["h_D20"], CONSTANTS["h_10D20"]))


get_distance_coefficients = CallableDict()



@get_distance_coefficients.add("base","site")
def get_distance_coefficients_1(kind, c3, c3_epsilon, C, imt, ctx):
    """
    Returns either the directly specified c3 value or the c3 from the
    existing tau_c3 distribution
    """
    if c3:
        # Use the c3 that has been defined on input
        return c3
    else:
        # Define the c3 as a number of standard deviation multiplied
        # by tau_c3
        return C["c3"] + (c3_epsilon * C["tau_c3"])




def _assign_feature_indices(tree, lons, lats):
    """
    Return the index of the containing feature for each (lon, lat) point,
    or -1 if the point is outside every feature. Uses a shapely STRtree
    spatial index to avoid scanning all polygons per call.
    """
    # -1 means point is not inside any feature
    assignment = np.full(len(lons), -1)

    # STRtree batch query: returns (point_idx, polygon_idx) pairs for all
    # points that fall inside at least one polygon
    pts = shapely.points(lons, lats)
    pt_idx, poly_idx = tree.query(pts, predicate='within')

    # If polygons overlap, keep the lowest polygon index to match the
    # first-match behaviour of the original iterate-shapes-in-order code.
    # Assigning in descending poly_idx order means lower indices overwrite
    # higher ones for any shared pt_idx.
    order = np.argsort(poly_idx)[::-1]
    assignment[pt_idx[order]] = poly_idx[order]

    return assignment


def _build_props_cache(props_list):
    """
    Precompute a {key: per-feature ndarray} cache from a list of GeoJSON
    feature property dicts, so lookups in compute() do not rebuild the
    same per-feature values array on every IMT.
    """
    cache = {}
    for k in props_list[0]:
        try:
            cache[k] = np.array(
                [np.nan if p[k] is None else float(p[k]) for p in props_list],
                dtype=float)
        except (TypeError, ValueError):
            pass  # skip non-numeric keys (names, codes, ...)
    return cache


def _lookup_property(feat_idx, prop_vals):
    """
    Return each point's value from a precomputed per-feature values array,
    or 0.0 for points outside every feature.
    """
    # Set array of zeros (one per input point) - any unassigned point will
    # end up keeping this zero value and therefore fallback to base coeff
    out = np.zeros(len(feat_idx))

    # Get mask marking the points which got assigned to a feature
    valid = feat_idx >= 0

    # Assign non-zero value to each point inside a feature
    out[valid] = prop_vals[feat_idx[valid]]

    return out





def get_distance_term(kind, c3, c3_epsilon, C, ctx, imt):
    """
    Returns the distance attenuation factor
    """
    h = _get_h(C, ctx.hypo_depth)
    rval = np.sqrt(ctx.rjb ** 2. + h ** 2.)
    rref_val = np.sqrt(CONSTANTS["Rref"] ** 2. + h ** 2.)
    if kind != 'regional':
        c3 = get_distance_coefficients(kind, c3, c3_epsilon, C, imt, ctx)
    f_r = (C["c1"] + C["c2"] * (ctx.mag - CONSTANTS["Mref"])) *\
        np.log(rval / rref_val) + (c3 * (rval - rref_val) / 100.)

    return f_r


def get_magnitude_scaling(C, mag):
    """
    Returns the magnitude scaling term
    """
    d_m = mag - CONSTANTS["Mh"]
    return np.where(mag <= CONSTANTS["Mh"],
                    C["e1"] + C["b1"] * d_m + C["b2"] * d_m ** 2.0,
                    C["e1"] + C["b3"] * d_m)




def get_dl2l(tec_vals, tec_feat_idx, imt_key, delta_l2l_epsilon):
    """
    Return rupture source specific delta_l2l values. A delta_l2l_epsilon
    value of +/- 1.6 gives the 95% confidence interval for delta_l2l.
    """
    dl2l_val = _lookup_property(tec_feat_idx, tec_vals[imt_key])
    dl2l_se = _lookup_property(tec_feat_idx, tec_vals[imt_key + '_se'])
    return dl2l_val + delta_l2l_epsilon * dl2l_se


def get_distance_coefficients_2(site_vals, site_feat_idx,
                                event_vals, event_feat_idx,
                                delta_c3_epsilon, C, imt_key, ctx):

    site = _lookup_property(site_feat_idx, site_vals[imt_key])
    site_se = _lookup_property(site_feat_idx, site_vals[imt_key + '_se'])

    event = _lookup_property(event_feat_idx, event_vals[imt_key])
    event_se = _lookup_property(event_feat_idx, event_vals[imt_key + '_se'])

    site_na = np.isnan(site)
    event_na = np.isnan(event)

    # NA -> 0 for the C3 contribution
    dc3_site_eff = np.where(site_na, 0.0, site)
    dc3_event_eff = np.where(event_na, 0.0, event)

    # Standard error
    # NA + NA       -> tau_c3
    # NA + real     -> sqrt(site_se^2 + event_se^2)
    # real + NA     -> sqrt(site_se^2 + event_se^2)
    # real + real   -> sqrt(site_se^2 + event_se^2)
    SE = np.where(
        site_na & event_na,
        C["tau_c3"],
        np.sqrt(site_se**2 + event_se**2)
    )


    return (
        C["c3"]
        + dc3_site_eff
        + dc3_event_eff
        + delta_c3_epsilon * SE
    )





def get_site_amplification(kind, extra, C, ctx, imt):
    """
    Apply the correct site amplification depending on the kind of GMPE
    """
    if kind == "base":  # no site amplification
        ampl = 0.
    elif kind in {"site", "regional"}:
        # Render with respect to 800 m/s reference Vs30
        sref = np.log(ctx.vs30 / 800.)
        ampl = (C["g0_vs30"] + C["g1_vs30"] * sref +
                C["g2_vs30"] * (sref ** 2.))
    return ampl


def get_tau(C,imt, mag):
    """
    Heteroskedastic Tau model 
    """
    tau = C["tau_event"] + C["d1"] * np.arcsinh(mag - CONSTANTS["Mref"])
    return tau


def get_stddevs(kind, ergodic, phi_s2s, C, ctx, imt):
    """
    Returns the heteroskedastic standard deviation model
    """
    mag = ctx.mag
    phi = C["phi_0"]
    if ergodic:
        if kind in {"site", "regional"}:
            phi = np.sqrt(phi ** 2.0 + C["phi_s2s_vs30"] ** 2.)
            tau = get_tau(C,imt,mag)
        else:
            phi = np.sqrt(phi ** 2. + C["phi_s2s"] ** 2.)
            tau = get_tau(C,imt,mag)
    return [np.sqrt(tau ** 2. + phi ** 2.), tau, phi]




