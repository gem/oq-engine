function generate_reference(author_directory, output_file)
% Generate the data-only reference CSV with the unmodified author function.
% GNU Octave 8.4.0 was used for the committed table.

addpath(author_directory);
codes1 = [0, 0, 0, -2, -3, -4, 0.01, 0.01, 0.3, 1, 2, 3, 10, ...
          0.1, 0.01, -1, -2, 0.075, 4, 0, -1, -3, -5];
codes2 = [0, -1, -2, -3, -4, -5, 0.01, 0, -1, -2, -3, -4, -5, ...
          1, 10, -3, -5, 0.75, 7.5, -5, -4, -3, -5];
distances = [0, 0, 0, 0, 0, 0, 5, 5, 5, 5, 5, 5, 20, 20, 20, 20, ...
             20, 100, 100, 100, 100, 100, 100];
labels1 = {'PGA', 'PGA', 'PGA', 'IA', 'CAV', 'RSD575', 'SA(0.01)', ...
           'SA(0.01)', 'SA(0.3)', 'SA(1)', 'SA(2)', 'SA(3)', 'SA(10)', ...
           'SA(0.1)', 'SA(0.01)', 'PGV', 'IA', 'SA(0.075)', 'SA(4)', ...
           'PGA', 'PGV', 'CAV', 'RSD595'};
labels2 = {'PGA', 'PGV', 'IA', 'CAV', 'RSD575', 'RSD595', 'SA(0.01)', ...
           'PGA', 'PGV', 'IA', 'CAV', 'RSD575', 'RSD595', 'SA(1)', ...
           'SA(10)', 'CAV', 'RSD595', 'SA(0.75)', 'SA(7.5)', 'RSD595', ...
           'RSD575', 'CAV', 'RSD595'};

file = fopen(output_file, 'w');
fprintf(file, 'imt1,imt2,distance,rho\n');
for index = 1:numel(distances)
    rho = Du_Ning_SpatialCorrelation_IMs(
        codes1(index), codes2(index), distances(index));
    fprintf(file, '%s,%s,%.15g,%.15g\n', labels1{index}, ...
            labels2{index}, distances(index), rho);
end
fclose(file);
end
