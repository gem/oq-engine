"""
Check that the summary tables of the routes in doc/api-reference/rest-api.rst
match the URL configurations of the WebUI (in every application mode) and of
the DbServer. When the routes change, regenerate the tables with

    python -m openquake.server.tests.routes_doc_test --update
"""
import os
import re
import sys
import json
import pathlib
import subprocess

import pytest

DOC = (pathlib.Path(__file__).parents[3] / 'doc' / 'api-reference' /
       'rest-api.rst')
BEGIN = '.. BEGIN ROUTES TABLES (generated by routes_doc_test.py)\n'
END = '.. END ROUTES TABLES\n'
UPDATE = 'python -m openquake.server.tests.routes_doc_test --update'
MODES = ['PUBLIC', 'RESTRICTED', 'READ_ONLY', 'AELO', 'IMPACT', 'TOOLS_ONLY']
# the names of the decorator closures, which are not the views
WRAPPERS = {'wrap', 'view', 'inner', '_wrapper_view', 'wrapper_view'}
# regex fragment -> readable placeholder, applied in order
PLACEHOLDERS = [
    (r'result/(\d+)', 'result/:result_id'),
    (r'run_scenario_calc_from_ses_rupture/(?P<rup_id>[0-9]+)',
     'run_scenario_calc_from_ses_rupture/:rup_id'),
    (r'log/(\d*):(\d*)', 'log/[:start]:[:stop]'),
    (r'extract/([-/_\.\w]+)', 'extract/:spec'),
    (r'download_png/([-/_\.\(\)\w]+)', 'download_png/:name'),
    (r'extract_html_table/([-/_\.\(\)\w]+)', 'extract_html_table/:name'),
    (r'v0/db/([^/]+)', 'v0/db/:action'),
    (r'v0/worker_([^/]+)', 'v0/worker_:action'),
    (r'<int:calc_id>', ':calc_id'),
    (r'<str:tag_name>', ':tag_name'),
    (r'(\d+)', ':calc_id'),
]
DBSERVER_INTRO = '''\
The DbServer serves only the following routes, independently from the
application mode (see :ref:`dbserver-api`):'''


# walk the decorators of a view and return (name, methods, auth), where
# methods come from require_http_methods or internal_view and auth from
# internal_view (None for the other views)
def _inspect(callback):
    name, methods, auth, todo, seen = None, [], None, [callback], set()
    while todo:
        fn = todo.pop()
        if id(fn) in seen or not callable(fn):
            continue
        seen.add(id(fn))
        fname = getattr(fn, '__name__', '')
        if fname not in WRAPPERS and getattr(
                fn, '__module__', '').startswith('openquake'):
            name = name or '%s.%s' % (fn.__module__, fname)
        if hasattr(fn, '__wrapped__'):
            todo.append(fn.__wrapped__)
        code = getattr(fn, '__code__', None)
        for var, cell in zip(code.co_freevars if code else (),
                             getattr(fn, '__closure__', None) or ()):
            try:
                value = cell.cell_contents
            except ValueError:  # empty cell
                continue
            if (isinstance(value, (list, tuple)) and value and all(
                    isinstance(v, str) and v.isupper() for v in value)):
                methods = methods or list(value)
            elif var == 'auth' and isinstance(value, bool):
                auth = value
            elif callable(value):
                todo.append(value)
    return name, methods, auth


# flatten the URL configuration into pairs (pattern string, callback)
def _flatten(patterns, prefix=''):
    from django.urls import URLResolver
    for pat in patterns:
        if isinstance(pat, URLResolver):
            yield from _flatten(pat.url_patterns, prefix + str(pat.pattern))
        else:
            yield prefix + str(pat.pattern), pat.callback


# convert a pattern into a route like /v1/calc/:calc_id/status
def _readable(pattern):
    # first the placeholders, since some regexes contain ^, as in [^/]
    route = pattern
    for regex, text in PLACEHOLDERS:
        route = route.replace(regex, text)
    return '/' + route.replace('^', '').replace('$', '')


# print as JSON the /v0 and /v1 routes of the current settings and mode;
# this runs in a separate process for each mode
def _dump_routes():
    import django
    django.setup()
    from django.conf import settings
    from django.urls import get_resolver
    exempt = [re.compile(expr.lstrip('/'))
              for expr in getattr(settings, 'LOGIN_EXEMPT_URLS', ())]
    rows = []
    for pattern, callback in _flatten(get_resolver().url_patterns):
        route = _readable(pattern)
        if route.startswith(('/v0/', '/v1/')):
            name, methods, auth = _inspect(callback)
            rows.append(dict(route=route, view=name, methods=methods,
                             auth=auth,
                             exempt=any(e.match(route[1:]) for e in exempt)))
    print(json.dumps(rows))


# collect the routes for the given (settings module, mode) pairs, running
# one process per pair in parallel
def _collect(pairs):
    procs = []
    for settings_module, mode in pairs:
        env = dict(os.environ, OQ_TEST='1', OQ_APPLICATION_MODE=mode,
                   DJANGO_SETTINGS_MODULE=settings_module)
        procs.append(subprocess.Popen(
            [sys.executable, '-m', 'openquake.server.tests.routes_doc_test',
             '--child'], env=env, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, text=True))
    results = []
    for proc in procs:
        out, err = proc.communicate()
        if proc.returncode:
            raise RuntimeError('Could not read the routes:\n' + err)
        # the JSON is the last line, after the possible warnings
        results.append(json.loads(out.strip().splitlines()[-1]))
    return results


# the authentication required by a route
def _auth(row):
    if row['auth'] is True or row['view'].endswith('views.on_same_fs'):
        return 'API key'
    if row['auth'] is False or row['exempt']:
        return 'none'
    return 'login'


def _list_table(header, rows, widths):
    lines = ['.. list-table::', '   :header-rows: 1',
             '   :widths: ' + ' '.join(map(str, widths)), '']
    for row in [header] + rows:
        lines.append('   * - ' + row[0])
        lines.extend('     - ' + cell for cell in row[1:])
    return '\n'.join(lines)


def routes_tables():
    """
    :returns: the RST tables of the routes of the WebUI and of the DbServer
    """
    pairs = [('openquake.server.settings', mode) for mode in MODES]
    pairs.append(('openquake.server.dbserver_settings', 'PUBLIC'))
    *by_mode, dbserver_rows = _collect(pairs)
    entries = {}  # route -> row, in the order of the URL configuration
    for mode, rows in zip(MODES, by_mode):
        for row in rows:
            entry = entries.setdefault(row['route'], dict(row, modes=set()))
            entry['modes'].add(mode)
            # the login exemptions exist only with authentication enabled
            entry['exempt'] = entry['exempt'] or row['exempt']
    webui = [['``%s``' % route, ' '.join(entry['methods']), _auth(entry)] +
             ['✓' if mode in entry['modes'] else '' for mode in MODES]
             for route, entry in entries.items()]
    dbserver = [['``%s``' % row['route'], ' '.join(row['methods']),
                 _auth(row)] for row in dbserver_rows]
    return '\n\n'.join([
        _list_table(['Route', 'Methods', 'Auth'] + MODES, webui,
                    [34, 10, 8] + [8] * len(MODES)),
        DBSERVER_INTRO,
        _list_table(['Route', 'Methods', 'Auth'], dbserver, [40, 15, 15])])


# return the text of the documentation and the position of the tables
def _read_doc():
    text = DOC.read_text(encoding='utf8')
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    return text, start, end


def test_routes_tables():
    if not DOC.exists():
        pytest.skip('the documentation is not available')
    text, start, end = _read_doc()
    assert text[start:end].strip() == routes_tables().strip(), (
        'The routes tables in %s do not match the URL configurations: '
        'regenerate them with `%s`' % (DOC, UPDATE))


def update():
    """
    Replace the routes tables in the documentation with the current ones
    """
    text, start, end = _read_doc()
    DOC.write_text(text[:start] + '\n' + routes_tables() + '\n\n' +
                   text[end:], encoding='utf8')
    print('Updated %s' % DOC)


if __name__ == '__main__':
    if sys.argv[1:] == ['--child']:
        _dump_routes()
    elif sys.argv[1:] == ['--update']:
        update()
    else:
        sys.exit('Usage: %s' % UPDATE)
